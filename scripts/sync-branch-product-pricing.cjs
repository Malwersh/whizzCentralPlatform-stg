'use strict';
// Bundle the same authoritative calculator for the merchant Lambda. No deployment.
const fs=require('node:fs'),path=require('node:path'),esbuild=require('../backend/wallet-service/node_modules/esbuild');
const root=path.resolve(__dirname,'..');
const result=esbuild.buildSync({absWorkingDir:root,entryPoints:[path.join(root,'backend/wallet-service/src/orderGoodsPricing.ts')],bundle:true,write:false,platform:'node',target:'node22',external:['@aws-sdk/*'],logLevel:'silent'});
const output='// Generated by sync-branch-product-pricing.cjs.\n'+result.outputFiles[0].text;
for(const target of ['../whizzMerchants-stg/backend/functions/shared/branch-product-pricing.js','backend/wallet-service/merchant-runtime/functions/shared/branch-product-pricing.js']){
 const file=path.resolve(root,target);
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output)throw Error('BRANCH_PRICING_OUT_OF_SYNC: '+target);}
 else {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,output);}
}
