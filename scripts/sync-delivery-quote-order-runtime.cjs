'use strict';
// Keep the customer order adapter on the same Money and Quote contracts as the pricing service.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ts=require('../backend/wallet-service/node_modules/typescript');
const destination=path.join(path.resolve(process.env.WIZZUSER_RUNTIME_ROOT||path.resolve(__dirname,'../../wizzuser-stg')),'backend/src/functions/create-order/quote-runtime');
const check=process.argv.includes('--check');
const sourceRoot=path.resolve(__dirname,'../backend/wallet-service/src');
const pending=['financeRollout','deliveryQuoteOrder','orderGoodsPricing','orderCommercialSource','deliveryPromotionSelection','deliveryPromotionCustomer','merchantPendingResponse'];
const visited=new Set();
const authorityFiles=['catalog','commercial-party'];
for(const name of pending){
 if(visited.has(name))continue;
 visited.add(name);
 const source=fs.readFileSync(path.resolve(__dirname,'../backend/wallet-service/src/'+name+'.ts'),'utf8');
 for(const match of source.matchAll(/(?:from\s*|require\s*\(\s*)['"]\.\/([A-Za-z0-9]+)['"]/g)){
  const dependency=match[1];
  if(!fs.existsSync(path.join(sourceRoot,dependency+'.ts')))throw Error('QUOTE_ORDER_DEPENDENCY_MISSING: '+dependency);
  pending.push(dependency);
 }
 const digest=crypto.createHash('sha256').update(source).digest('hex');
 const result=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS,strict:true},reportDiagnostics:true});
 if(result.diagnostics?.some(d=>d.category===ts.DiagnosticCategory.Error))throw Error('QUOTE_ORDER_COMPILE_FAILED');
 let compiled=result.outputText;
 for(const dependency of authorityFiles)compiled=compiled.replaceAll('../../staff-service/'+dependency,'./authority/'+dependency);
 // Keep the same authority implementations while relocating their paths for this Lambda.
 if(compiled.includes('../../staff-service/'))throw Error('QUOTE_ORDER_AUTHORITY_DEPENDENCY_UNSUPPORTED');
 const output='// Generated by sync-delivery-quote-order-runtime.cjs. Source SHA256: '+digest+'\n'+compiled;
 const target=path.join(destination,name+'.js');
 if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('QUOTE_ORDER_RUNTIME_OUT_OF_SYNC: '+name);}
 else{fs.mkdirSync(destination,{recursive:true});fs.writeFileSync(target,output);}
}

const authorityVisited=new Set();
for(const name of authorityFiles){
 if(authorityVisited.has(name))continue;authorityVisited.add(name);
 const source=fs.readFileSync(path.resolve(__dirname,'../backend/staff-service/'+name+'.js'),'utf8');
 for(const match of source.matchAll(/require\s*\(\s*['"]\.\/([A-Za-z0-9_-]+)['"]/g))authorityFiles.push(match[1]);
 const target=path.join(destination,'authority',name+'.js');
 if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==source)throw Error('QUOTE_ORDER_AUTHORITY_OUT_OF_SYNC: '+name);}
 else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,source);}
}
